        title: "latence de réveil du timer (retard sur l'échéance)",
        mode: "timer",
        common,
        policy,
        warmup,
        meta: vec![("interval_us", args.interval.to_string())],
    };
    report::present(&run, &measurement, irqs.finish())
}
